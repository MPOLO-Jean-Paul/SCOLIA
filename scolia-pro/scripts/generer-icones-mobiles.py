#!/usr/bin/env python3
"""Embed pinned Google Material Symbols Rounded as native mobile geometries (Apache-2.0)."""
import argparse
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
from urllib.request import urlopen
from urllib.error import HTTPError
from xml.etree import ElementTree as E
import hashlib
import json

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
parser.add_argument('--cache', type=Path, default=Path('/tmp/scolia-material-symbols'))
args = parser.parse_args()
root = Path(__file__).resolve().parents[1] / 'src/Scolia.Bureau'
assets = root / 'Assets/MaterialSymbols'
config = json.loads((assets / 'catalogue.json').read_text())
args.cache.mkdir(parents=True, exist_ok=True)

def source(name):
    path = f'symbols/web/{name}/materialsymbolsrounded/{name}_fill1_24px.svg'
    target = args.cache / (config['commit'] + '-' + name + '.svg')
    regular = args.cache / (config['commit'] + '-' + name + '-regular.svg')
    if not target.exists() and regular.exists():
        return name, f'symbols/web/{name}/materialsymbolsrounded/{name}_24px.svg', regular.read_bytes()
    if not target.exists():
        try:
            with urlopen(f'https://raw.githubusercontent.com/google/material-design-icons/{config["commit"]}/{path}', timeout=25) as response:
                target.write_bytes(response.read())
        except HTTPError as error:
            if error.code != 404:
                raise
            path = f'symbols/web/{name}/materialsymbolsrounded/{name}_24px.svg'
            target = args.cache / (config['commit'] + '-' + name + '-regular.svg')
            if not target.exists():
                try:
                    with urlopen(f'https://raw.githubusercontent.com/google/material-design-icons/{config["commit"]}/{path}', timeout=25) as response:
                        target.write_bytes(response.read())
                except HTTPError as missing:
                    raise RuntimeError(f'{name}: {missing}') from missing
    return name, path, target.read_bytes()

with ThreadPoolExecutor(max_workers=8) as pool:
    sources = {name: (path, data) for name, path, data in pool.map(source, sorted(set(config['symbols'].values())))}
lines = ['// Generated by scripts/generer-icones-mobiles.py. Google Material Symbols, Apache-2.0.',
         'using Material.Icons;', '', 'namespace Scolia.Bureau.Infrastructure;', '',
         'public static partial class MobileArtwork', '{',
         '    private static Dictionary<MaterialIconKind, string> CreateSymbols()', '    {',
         '        var symbols = new Dictionary<MaterialIconKind, string>();']
manifest = {key: config[key] for key in ['source', 'commit', 'variant', 'fill', 'opticalSize', 'weight', 'license']}
manifest['symbols'] = []
for alias, name in sorted(config['symbols'].items()):
    path, data = sources[name]
    svg = E.fromstring(data)
    assert svg.attrib['viewBox'] == '0 -960 960 960', (name, svg.attrib)
    nodes = [node for node in svg.iter() if node.tag.endswith('path')]
    assert nodes and all('d' in node.attrib for node in nodes), name
    geometry = ('F0 ' if any(n.attrib.get('fill-rule') == 'evenodd' for n in nodes) else 'F1 ') + ' '.join(n.attrib['d'] for n in nodes)
    lines.append(f'        Add(symbols, {json.dumps(alias)}, {json.dumps(geometry)});')
    manifest['symbols'].append({'alias': alias, 'name': name, 'fill': 1 if '_fill1_' in path else 0,
                                'path': path, 'sha256': hashlib.sha256(data).hexdigest()})
lines += ['        return symbols;', '    }', '', '    private static HashSet<MaterialIconKind> CreateGreen() =>',
          '        ' + json.dumps(' '.join(config['green'])) + ".Split(' ').Select(Enum.Parse<MaterialIconKind>).ToHashSet();", '',
          '    private static void Add(Dictionary<MaterialIconKind, string> target, string alias, string geometry)',
          '    {', '        if (Enum.TryParse<MaterialIconKind>(alias, out var kind)) target[kind] = geometry;',
          '    }', '}', '']
generated = {root / 'Infrastructure/MobileArtwork.Data.cs': '\n'.join(lines),
             assets / 'manifest.json': json.dumps(manifest, ensure_ascii=False, indent=2) + '\n'}
for path, data in generated.items():
    if args.check:
        if path.read_text() != data:
            raise SystemExit('Resource out of date: ' + str(path))
    else:
        path.write_text(data)
license_path = assets / 'LICENSE.txt'
if not license_path.exists():
    if args.check:
        raise SystemExit('Missing Google Material Symbols license: ' + str(license_path))
    with urlopen(f'https://raw.githubusercontent.com/google/material-design-icons/{config["commit"]}/LICENSE', timeout=25) as response:
        license_path.write_bytes(response.read())
print(f'{len(config["symbols"])} identifiers; {len(sources)} original Material Symbols Rounded. Pinned {config["commit"]}.')
