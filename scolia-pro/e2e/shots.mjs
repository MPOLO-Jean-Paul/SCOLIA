import { chromium } from '@playwright/test';
const base = 'http://localhost:5080';
const out = process.argv[2] ?? '/tmp/scolia-run';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: 'fr-FR' });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(base + '/');
await page.waitForURL(/installation/);
await page.screenshot({ path: `${out}/01-installation.png`, fullPage: true });
await page.getByLabel("Nom de l'établissement").fill('Institut Technique Médical Démo');
await page.getByLabel('Sigle').fill('ITM Démo');
await page.getByLabel('Nom complet').fill('Jean-Paul Administrateur');
await page.getByLabel('Mot de passe', { exact: true }).fill('Scolia2026!');
await page.getByLabel('Confirmer le mot de passe').fill('Scolia2026!');
await page.getByText('Ajouter des données de démonstration').click();
await page.getByRole('button', { name: 'Installer SCOLIA' }).click();
await page.waitForURL(base + '/');
await page.getByText('Recettes par mois').waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/02-tableau-de-bord.png`, fullPage: true });
await page.goto(base + '/apprenants');
await page.locator('table.data tbody tr').first().waitFor();
await page.screenshot({ path: `${out}/03-apprenants.png` });
await page.locator('table.data tbody tr').first().click();
await page.getByText('Situation financière').waitFor();
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/04-fiche.png`, fullPage: true });
await page.goto(base + '/encaisser');
await page.getByPlaceholder('Matricule ou nom').fill('INF1');
await page.locator('.card button.btn.ghost').first().click();
await page.getByLabel(/Montant versé/).fill('55000');
await page.getByText('Répartition du paiement').waitFor();
await page.locator('text=Reste de l’année après ce reçu').waitFor();
await page.screenshot({ path: `${out}/05-encaisser.png`, fullPage: true });
await page.getByRole('button', { name: /Valider le paiement/ }).click();
await page.getByText('Paiement enregistré').waitFor();
await page.screenshot({ path: `${out}/06-recu-ok.png` });
await page.goto(base + '/recouvrement');
await page.locator('table.data tbody tr').first().waitFor();
await page.screenshot({ path: `${out}/07-recouvrement.png` });
await page.goto(base + '/caisse');
await page.getByText('Mouvements de la période').waitFor();
await page.screenshot({ path: `${out}/08-caisse.png` });
await page.goto(base + '/notes');
await page.getByText('Résultats et bulletins').click();
await page.locator('table.data tbody tr').first().waitFor();
await page.screenshot({ path: `${out}/09-resultats.png` });
await page.keyboard.press('Control+k');
await page.getByPlaceholder(/Nom, matricule/).fill('kasongo');
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/10-palette.png` });
await page.keyboard.press('Escape');
await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
await page.goto(base + '/');
await page.evaluate(() => localStorage.setItem('scolia.theme', 'sombre'));
await page.reload();
await page.getByText('Recettes par mois').waitFor();
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/11-sombre.png` });
await page.context().clearCookies();
await page.evaluate(() => localStorage.setItem('scolia.theme', 'clair'));
await page.goto(base + '/connexion');
await page.getByRole('button', { name: 'Se connecter' }).waitFor();
await page.screenshot({ path: `${out}/12-connexion.png` });
console.log(errors.length ? errors.join('\n') : 'Aucune erreur JavaScript.');
await browser.close();
